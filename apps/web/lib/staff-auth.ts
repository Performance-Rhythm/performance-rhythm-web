const SESSION_CONTEXT = "performance-rhythm-staff-session-v1";

export async function createStaffSessionToken(username: string, password: string) {
  const bytes = new TextEncoder().encode(`${SESSION_CONTEXT}\0${username}\0${password}`);
  const digest = await crypto.subtle.digest("SHA-256", bytes);
  return Array.from(new Uint8Array(digest), (byte) => byte.toString(16).padStart(2, "0")).join("");
}

export function secureEqual(left: string, right: string) {
  const maxLength = Math.max(left.length, right.length);
  let difference = left.length ^ right.length;
  for (let index = 0; index < maxLength; index += 1) {
    difference |= (left.charCodeAt(index) || 0) ^ (right.charCodeAt(index) || 0);
  }
  return difference === 0;
}
